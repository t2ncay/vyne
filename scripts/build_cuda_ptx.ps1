# Compile the @device CUDA kernels to PTX and regenerate
# vyne/runtime/detail/vyne_cuda_ptx.h.
#
# nvcc on Windows needs cl.exe (and the Windows SDK) on PATH, so this
# script enters the Visual Studio developer environment via vcvars64.bat.
# The PTX is embedded as a C string; the Vyne runtime loads nvcuda.dll
# at process start and JIT-compiles the PTX on the target GPU.
#
# Usage (from the repo root):
#   pwsh -File scripts/build_cuda_ptx.ps1

$ErrorActionPreference = 'Stop'

$ScriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$Root      = Split-Path -Parent $ScriptDir
$CuPath    = Join-Path $Root 'vyne/runtime/device/cuda/kernels.cu'
$Header    = Join-Path $Root 'vyne/runtime/detail/vyne_cuda_ptx.h'
$PtxPath   = Join-Path $env:TEMP 'vyne_cuda_kernels.ptx'

if (-not (Test-Path $CuPath)) {
    throw "CUDA kernels not found at $CuPath"
}

# --- locate vcvars64.bat ---------------------------------------------------
$VcVars = $null
$VsWhere = Join-Path ${env:ProgramFiles(x86)} 'Microsoft Visual Studio/Installer/vswhere.exe'
if (Test-Path $VsWhere) {
    $install = & $VsWhere -latest -property installationPath 2>$null
    if ($install) {
        $candidate = Join-Path $install 'VC/Auxiliary/Build/vcvars64.bat'
        if (Test-Path $candidate) { $VcVars = $candidate }
    }
}
if (-not $VcVars) {
    $VcVars = Get-ChildItem 'C:\Program Files\Microsoft Visual Studio' `
        -Recurse -Filter vcvars64.bat -ErrorAction SilentlyContinue |
        Select-Object -First 1 -ExpandProperty FullName
}
if (-not $VcVars) {
    throw 'vcvars64.bat not found. Install the Visual Studio C++ build tools.'
}

# --- run nvcc inside the VS developer environment --------------------------
$Batch = Join-Path $env:TEMP 'vyne_build_cuda_ptx.bat'
@"
@echo off
call "$VcVars" >nul
nvcc -ptx -arch=compute_80 -o "$PtxPath" "$CuPath"
"@ | Set-Content -Path $Batch -Encoding ASCII

if (Test-Path $PtxPath) { Remove-Item -LiteralPath $PtxPath -Force }
cmd /c "`"$Batch`""
if ($LASTEXITCODE -ne 0 -or -not (Test-Path $PtxPath)) {
    throw "nvcc failed (exit $LASTEXITCODE)"
}

# --- emit the embedded C string -------------------------------------------
$lines = Get-Content -Path $PtxPath
$out = New-Object System.Collections.Generic.List[string]
$out.Add('// SPDX-License-Identifier: MIT')
$out.Add('// Copyright (c) 2026 Tuncay Gafarli')
$out.Add('//')
$out.Add('// Generated by scripts/build_cuda_ptx.ps1 from')
$out.Add('// vyne/runtime/device/cuda/kernels.cu. Do not edit by hand.')
$out.Add('#pragma once')
$out.Add('')
$out.Add('static const char* VYNE_CUDA_PTX =')

foreach ($raw in $lines) {
    $line = $raw.TrimEnd("`r")
    $esc = $line.Replace('\', '\\').Replace('"', '\"').Replace("`t", '\t')
    $out.Add('    "' + $esc + '\n"')
}

# Drop the trailing newline from the last fragment and terminate the string.
$last = $out[$out.Count - 1]
if ($last.EndsWith('\\n"')) {
    $last = $last.Substring(0, $last.Length - 3) + '"'
}
$out[$out.Count - 1] = $last + ';'

$utf8 = New-Object System.Text.UTF8Encoding($false)
[System.IO.File]::WriteAllLines($Header, $out, $utf8)

$size = (Get-Item $Header).Length
Write-Host "wrote $Header ($size bytes, $($lines.Count) PTX lines)"
