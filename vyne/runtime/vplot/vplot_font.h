// Shared 5x7 bitmap metrics on every surface: six-pixel advance, eight-pixel
// line height. These compact glyphs are authored for vplot, not platform fonts.
static inline const uint8_t* vp_glyph(unsigned char ch) {
    static const uint8_t upper[26][7] = {
        {14,17,17,31,17,17,17},{30,17,17,30,17,17,30},{14,17,16,16,16,17,14},
        {30,17,17,17,17,17,30},{31,16,16,30,16,16,31},{31,16,16,30,16,16,16},
        {14,17,16,23,17,17,15},{17,17,17,31,17,17,17},{14,4,4,4,4,4,14},
        {7,2,2,2,18,18,12},{17,18,20,24,20,18,17},{16,16,16,16,16,16,31},
        {17,27,21,21,17,17,17},{17,25,21,19,17,17,17},{14,17,17,17,17,17,14},
        {30,17,17,30,16,16,16},{14,17,17,17,21,18,13},{30,17,17,30,20,18,17},
        {15,16,16,14,1,1,30},{31,4,4,4,4,4,4},{17,17,17,17,17,17,14},
        {17,17,17,17,17,10,4},{17,17,17,21,21,21,10},{17,17,10,4,10,17,17},
        {17,17,10,4,4,4,4},{31,1,2,4,8,16,31}
    };
    static const uint8_t lower[26][7] = {
        {0,0,14,1,15,17,15},{16,16,30,17,17,17,30},{0,0,14,16,16,17,14},
        {1,1,15,17,17,17,15},{0,0,14,17,31,16,14},{6,9,8,28,8,8,8},
        {0,15,17,17,15,1,14},{16,16,30,17,17,17,17},{4,0,12,4,4,4,14},
        {2,0,6,2,2,18,12},{16,16,18,20,24,20,18},{12,4,4,4,4,4,14},
        {0,0,26,21,21,21,21},{0,0,30,17,17,17,17},{0,0,14,17,17,17,14},
        {0,30,17,17,30,16,16},{0,15,17,17,15,1,1},{0,0,22,25,16,16,16},
        {0,0,15,16,14,1,30},{8,8,28,8,8,9,6},{0,0,17,17,17,19,13},
        {0,0,17,17,17,10,4},{0,0,17,17,21,21,10},{0,0,17,10,4,10,17},
        {0,17,17,17,15,1,14},{0,0,31,2,4,8,31}
    };
    static const uint8_t digits[10][7] = {
        {14,17,19,21,25,17,14},{4,12,4,4,4,4,14},{14,17,1,2,4,8,31},
        {30,1,1,14,1,1,30},{2,6,10,18,31,2,2},{31,16,16,30,1,1,30},
        {14,16,16,30,17,17,14},{31,1,2,4,8,8,8},{14,17,17,14,17,17,14},
        {14,17,17,15,1,1,14}
    };
    static const uint8_t punctuation[][7] = {
        {0,0,0,0,0,0,0}, {14,17,1,2,4,0,4}, {0,0,0,31,0,0,0},
        {0,4,4,31,4,4,0},{0,0,0,0,0,6,6},{0,6,6,0,6,6,0},
        {1,2,2,4,8,8,16},{2,4,8,8,8,4,2},{8,4,2,2,2,4,8},
        {0,0,31,0,31,0,0},{25,25,2,4,8,19,19},{0,0,0,0,0,4,8},
        {14,8,8,8,8,8,14},{14,2,2,2,2,2,14},{0,0,0,0,0,0,31},
        {4,4,4,4,4,0,4},{10,10,0,0,0,0,0},{0,0,21,14,31,14,21}
    };
    if (ch >= 'A' && ch <= 'Z') return upper[ch-'A'];
    if (ch >= 'a' && ch <= 'z') return lower[ch-'a'];
    if (ch >= '0' && ch <= '9') return digits[ch-'0'];
    const char* keys = " ?-+.:/()=%,[]_!\"*";
    for (int i=0; keys[i]; ++i) if (ch == (unsigned char)keys[i]) return punctuation[i];
    return punctuation[1];
}
