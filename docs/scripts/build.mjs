#!/usr/bin/env node
// ---------------------------------------------------------------------------
// build.mjs — regenerate every page + the search index from
// content/*.html and nav.json.
//
//   node scripts/build.mjs            # build
//   node scripts/build.mjs --clean    # also delete orphaned pages/*.html
// ---------------------------------------------------------------------------

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { renderPage, flattenNav } from "./lib/layout.mjs";
import { stripHtml, escapeHtml } from "./lib/slug.mjs";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const argv = process.argv.slice(2);
const rootIndex = argv.indexOf("--root");
if (rootIndex !== -1 && (!argv[rootIndex + 1] || argv[rootIndex + 1].startsWith("--"))) {
  throw new Error("--root requires a directory");
}
const ROOT = rootIndex === -1 ? path.resolve(__dirname, "..") : path.resolve(argv[rootIndex + 1]);
const CONTENT_DIR = path.join(ROOT, "content");
const PAGES_DIR = path.join(ROOT, "pages");
const ASSETS_DIR = path.join(ROOT, "assets");
const NAV_FILE = path.join(ROOT, "nav.json");

const CLEAN = argv.includes("--clean");

function die(msg) {
  console.error(`\n✖ ${msg}\n`);
  process.exit(1);
}

// --- load nav ---------------------------------------------------------------
if (!fs.existsSync(NAV_FILE)) die("nav.json not found. Run extract-legacy first.");
let nav;
try {
  nav = JSON.parse(fs.readFileSync(NAV_FILE, "utf8"));
} catch (e) {
  die(`nav.json is not valid JSON: ${e.message}`);
}

const flat = flattenNav(nav);
const knownIds = new Set(flat.map((it) => it.id));

// --- helpers ----------------------------------------------------------------
function rewritelinks(html, rel) {
  return html.replace(
    /<a\b([^>]*?)data-page="([^"]+)"([^>]*)>/g,
    (_m, pre, id, post) => {
      const [pageId, fragment] = id.split("#", 2);
      if (!knownIds.has(pageId)) die(`Unknown internal page: ${id}`);
      const target = (pageId === "intro" ? "index.html" : `pages/${pageId}.html`) +
        (fragment ? `#${fragment}` : "");
      const attrs = `${pre}${post}`.replace(/\s+/g, " ").trim();
      const href = `${rel}${target}`;
      return `<a${attrs ? " " + attrs : ""} href="${href}">`;
    },
  );
}

// Legacy code blocks only had a copy button on some headers; give every block
// one so the interaction is consistent. No visible content is changed.
function ensureCopyButtons(html) {
  return html.replace(
    /(<div class="code-header">)([\s\S]*?)(<\/div>)/g,
    (m, open, inner, close) => {
      if (/copy-btn/.test(inner)) return m;
      return (
        open +
        inner +
        '<button class="copy-btn" type="button"><i class="far fa-copy"></i> copy</button>' +
        close
      );
    },
  );
}

function extractHeadings(html) {
  const headings = [];
  const re = /<h([23])\s+id="([^"]+)"[^>]*>([\s\S]*?)<\/h\1>/g;
  let m;
  while ((m = re.exec(html)) !== null) {
    headings.push({ level: Number(m[1]), id: m[2], text: stripHtml(m[3]) });
  }
  return headings;
}

// --- build pages ------------------------------------------------------------
fs.mkdirSync(PAGES_DIR, { recursive: true });
const searchEntries = [];
const written = new Set();
const report = [];

for (const item of flat) {
  const contentFile = path.join(CONTENT_DIR, `${item.id}.html`);
  if (!fs.existsSync(contentFile)) {
    die(`Missing content file: content/${item.id}.html (referenced by nav.json)`);
  }
  const raw = fs.readFileSync(contentFile, "utf8");

  const isIntro = item.id === "intro";
  const rel = isIntro ? "" : "../";
  const outFile = isIntro ? path.join(ROOT, "index.html") : path.join(PAGES_DIR, `${item.id}.html`);

  const content = ensureCopyButtons(rewritelinks(raw, rel));
  const page = renderPage({ nav, item, group: item.group, content, rel });
  fs.writeFileSync(outFile, page);
  written.add(path.resolve(outFile));
  report.push({
    id: item.id,
    group: item.group,
    title: item.title,
    output: path.relative(ROOT, outFile),
    headings: extractHeadings(content).length,
  });

  searchEntries.push({
    id: item.id,
    title: item.title,
    group: item.group,
    path: isIntro ? "index.html" : `pages/${item.id}.html`,
    headings: extractHeadings(content),
    text: stripHtml(content).slice(0, 6000),
  });
}

// --- search index -----------------------------------------------------------
fs.mkdirSync(ASSETS_DIR, { recursive: true });
const indexJs =
  "// AUTO-GENERATED by scripts/build.mjs — do not edit by hand.\n" +
  "window.VYNE_SEARCH = " +
  JSON.stringify(searchEntries) +
  ";\n";
fs.writeFileSync(path.join(ASSETS_DIR, "search-index.js"), indexJs);

// --- clean orphans ----------------------------------------------------------
let removed = 0;
if (CLEAN && fs.existsSync(PAGES_DIR)) {
  for (const f of fs.readdirSync(PAGES_DIR)) {
    if (!f.endsWith(".html")) continue;
    const abs = path.resolve(PAGES_DIR, f);
    if (!written.has(abs)) {
      fs.unlinkSync(abs);
      removed++;
    }
  }
}

console.log(`\n✔ Built ${flat.length} pages`);
console.table(report);
console.log(`  Search index: ${searchEntries.length} sections`);
if (CLEAN) console.log(`  Removed ${removed} orphaned page(s)`);
